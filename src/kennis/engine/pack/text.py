"""Editing a pack file as text, keeping what the person wrote.

`pack add`, `pack remove` and `pack update` all change a pack file, and the
person edits it too (Brian, 2026-10-26: "like a package.json with npm, or a
pyproject.toml with uv"). **The file is edited as text, never dumped**:
`yaml.dump` of the parsed pack would lose the editor header, every comment
and the person's key order. Positions come from `yaml.compose`, whose nodes
carry marks, and only the lines concerned change. A caller parses what it
made before it writes, so a defect here is a refusal, never a half-written
file.

**Each entry kennis writes is a mapping in braces, one key per line**, in
`FIELD_ORDER`, and set off from the next by a blank line (Brian,
2026-10-28, #558): a paper's forty authors read as one item, not as forty
lines that might belong to the next. **An entry kennis changes is written
again whole** (`with_entry`), so a hand-written block entry or one on one
line is edited as easily as one kennis wrote; what lies between entries is
the person's and stays, and a comment inside the entry changed is lost.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Final

import yaml
from yaml.nodes import MappingNode, Node, ScalarNode, SequenceNode

from kennis.engine.errors import InputError, PackInvalid
from kennis.engine.literature.identifiers import identifier_if_reference

type Value = str | int | list[str]
type Fields = list[tuple[str, Value]]
# An entry's keys and values as YAML read them, so possibly anything a
# person wrote; rendered back as written.
type Written = Sequence[tuple[str, object]]

# The order each section's entries are written in, by the keys from the
# root to the section. For a paper, what the person names it by first and
# the longest last; a key not listed keeps its place after these.
FIELD_ORDER: Final[Mapping[tuple[str, ...], tuple[str, ...]]] = {
    ("corpus", "literature"): (
        "identifier",
        "url",
        "file",
        "citekey",
        "title",
        "year",
        "group",
        "authors",
    ),
    ("corpus", "docs"): ("project", "base_url", "version", "pages", "exclude"),
    ("corpus", "notes"): (
        "source",
        "url",
        "file",
        "title",
        "group",
        "include",
        "exclude",
    ),
    ("context",): ("source", "group", "include", "exclude"),
}

GENERATED_MARKER: Final = "# Generated by `kennis pack update` - do not hand-edit."


def read_pack_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise PackInvalid(f"{path} could not be read: {error}") from error


def composed(text: str) -> MappingNode:
    node = yaml.compose(text)
    if not isinstance(node, MappingNode):
        raise PackInvalid("a pack file is a mapping of sections")
    return node


def child(mapping: MappingNode, key: str) -> tuple[ScalarNode, Node] | None:
    for key_node, value_node in mapping.value:
        if isinstance(key_node, ScalarNode) and key_node.value == key:
            return key_node, value_node
    return None


def node_at(root: MappingNode, keys: Sequence[str]) -> Node | None:
    """The node `keys` names, a digit naming a sequence's item."""
    node: Node = root
    for key in keys:
        if isinstance(node, SequenceNode) and key.isdigit():
            node = node.value[int(key)]
            continue
        if not isinstance(node, MappingNode):
            return None
        found = child(node, key)
        if found is None:
            return None
        node = found[1]
    return node


def last_line(node: Node, lines: Sequence[str]) -> int:
    """The last line holding a character of `node`.

    A block collection's end mark is the next token's position, which can
    be lines further on past comments, so the leaves are asked instead, and
    a line that is blank or only a comment is never counted.
    """
    if isinstance(node, ScalarNode) or getattr(node, "flow_style", False):
        line = (
            node.end_mark.line if node.end_mark.column > 0 else node.end_mark.line - 1
        )
    elif isinstance(node, MappingNode):
        line = max(last_line(value, lines) for pair in node.value for value in pair)
    elif isinstance(node, SequenceNode):
        line = max(last_line(item, lines) for item in node.value)
    else:
        line = node.end_mark.line
    while line > node.start_mark.line and _is_filler(lines[line]):
        line -= 1
    return line


def _is_filler(line: str) -> bool:
    stripped = line.strip()
    return not stripped or stripped.startswith("#")


def ordered(section: Sequence[str], item: Written) -> list[tuple[str, object]]:
    """`item` in the section's order, an identifier written the one way
    kennis spells it (`doi:` and a trailing full stop gone, an arXiv DOI
    the arXiv identifier), which is the spelling the entry's key has."""
    order = FIELD_ORDER.get(tuple(section), ())
    ranked = sorted(
        enumerate(item),
        key=lambda pair: (
            order.index(pair[1][0]) if pair[1][0] in order else len(order),
            pair[0],
        ),
    )
    canonical: list[tuple[str, object]] = []
    for _, (key, value) in ranked:
        if key == "identifier" and isinstance(value, str):
            parsed = identifier_if_reference(value)
            value = value if parsed is None else parsed.value
        canonical.append((key, value))
    return canonical


def rendered(item: Written, dash: int) -> list[str]:
    """One sequence item, in braces with one key per line: the brace on
    the dash's line, the keys two further in, the closing brace under the
    opening one. A list is one value a line. Strings through `json.dumps`,
    a YAML double-quoted scalar that keeps the file ASCII whatever a title
    holds."""
    keys = " " * (dash + 4)
    lines = [f"{' ' * dash}- {{\n"]
    for key, value in item:
        if isinstance(value, list) and value:
            lines.append(f"{keys}{key}: [\n")
            lines.extend(f"{keys}  {scalar(one)},\n" for one in value)
            lines.append(f"{keys}],\n")
        else:
            lines.append(f"{keys}{key}: {scalar(value)},\n")
    lines.append(f"{' ' * (dash + 2)}}}\n")
    return lines


def scalar(value: object) -> str:
    """`value` as YAML flow text: JSON is, for every value YAML reads."""
    if isinstance(value, int) and not isinstance(value, bool):
        return str(value)
    return json.dumps(value)


def appended(text: str, section: Sequence[str], item: Fields) -> str:
    """`text` with one item added at the end of the sequence `section` names,
    creating the sequence, and the mapping holding it, where missing."""
    lines = text.splitlines(keepends=True)
    root = composed(text)
    written = ordered(section, item)
    node = node_at(root, section)
    if isinstance(node, SequenceNode) and node.value:
        if node.flow_style:
            raise InputError(
                f"{'.'.join(section)} is written as a flow list; write it as a "
                "block list, one item per line, to add to it"
            )
        _, dash = dash_of(text, node.value[-1])
        at = last_line(node, lines) + 1
        return "".join([*lines[:at], "\n", *rendered(written, dash), *lines[at:]])

    return _with_a_new_list(text, section, written)


def dash_of(text: str, item: Node) -> tuple[int, int]:
    """The line and column of the dash that begins sequence item `item`:
    on the item's first line, or alone on a line above it."""
    before = text[: item.start_mark.index].rstrip()
    if not before.endswith("-"):
        raise PackInvalid("a list item kennis edits begins with a dash")
    index = len(before) - 1
    return before.count("\n"), index - (before.rfind("\n") + 1)


def with_entry(text: str, section: Sequence[str], index: int, item: Written) -> str:
    """`text` with item `index` of the sequence `section` names written
    again as `item`, from its dash to its last character, in kennis's form.
    Lines around it are untouched; a comment inside it is not kept."""
    lines = text.splitlines(keepends=True)
    node = node_at(composed(text), (*section, str(index)))
    if node is None:
        raise PackInvalid(f"{'.'.join(section)} has no entry {index + 1}")
    line, dash = dash_of(text, node)
    if lines[line][:dash].strip():
        raise PackInvalid(
            f"entry {index + 1} of {'.'.join(section)} shares its line with "
            "another; give it a line of its own for kennis to edit it"
        )
    end = last_line(node, lines)
    new = rendered(ordered(section, item), dash)
    return "".join([*lines[:line], *new, *lines[end + 1 :]])


def entry_written(text: str, section: Sequence[str], index: int) -> Written:
    """Item `index` of the sequence `section` names, as YAML reads it."""
    document: object = yaml.safe_load(text)
    for key in section:
        document = document.get(key) if isinstance(document, dict) else None
    if not isinstance(document, list) or not isinstance(document[index], dict):
        raise PackInvalid(f"entry {index + 1} of {'.'.join(section)} is not a mapping")
    return [(str(key), value) for key, value in document[index].items()]


def with_fields(text: str, section: Sequence[str], index: int, fields: Fields) -> str:
    """`text` with `fields` added to item `index` of `section`, the entry
    written again whole in kennis's form; a key it has already is kept."""
    held = entry_written(text, section, index)
    present = {key for key, _ in held}
    added = [(key, value) for key, value in fields if key not in present]
    return with_entry(text, section, index, [*held, *added])


def _with_a_new_list(text: str, section: Sequence[str], item: Written) -> str:
    """`text` with the list `section` names, which holds no items, made to
    hold `item`: an empty `[]` or a bare key is written out, a missing key
    is added to its mapping, and a missing mapping is made too - the only
    one that can be is `corpus`, because the root always exists."""
    lines = text.splitlines(keepends=True)
    root = composed(text)
    *parents, key = section
    parent = node_at(root, parents) if parents else root
    found = child(parent, key) if isinstance(parent, MappingNode) else None
    if found is not None:
        return _filled(lines, found, item, named=".".join(section))
    if isinstance(parent, MappingNode) and parent.value and not parent.flow_style:
        column = parent.value[0][0].start_mark.column
        new = [f"{' ' * column}{key}:\n", *rendered(item, column + 2)]
        if not parents:
            return _above_the_block(lines, new)
        at = last_line(parent, lines) + 1
        return "".join([*lines[:at], *new, *lines[at:]])
    assert len(parents) == 1, section
    holder = child(root, parents[0])
    new = rendered(item, 4)
    if holder is None:
        return _above_the_block(lines, [f"{parents[0]}:\n", f"  {key}:\n", *new])
    return _filled(lines, holder, [], named=parents[0], inner=[f"  {key}:\n", *new])


def _filled(
    lines: list[str],
    found: tuple[ScalarNode, Node],
    item: Written,
    *,
    named: str,
    inner: list[str] | None = None,
) -> str:
    """A key whose value is `[]`, `{}` or nothing, given lines below it:
    `item` as its list's first item, or the `inner` lines of a mapping."""
    key_node, value = found
    empty_collection = (
        isinstance(value, SequenceNode | MappingNode)
        and value.flow_style
        and not value.value
    )
    null = isinstance(value, ScalarNode) and value.tag == "tag:yaml.org,2002:null"
    if not (empty_collection or null):
        raise InputError(
            f"{named} is written on one line; write it as a block, one item "
            "per line, to add to it"
        )
    line = key_node.start_mark.line
    if empty_collection:
        text = lines[line]
        lines[line] = (
            text[: value.start_mark.column].rstrip() + text[value.end_mark.column :]
        )
    new = inner if inner is not None else rendered(item, key_node.start_mark.column + 2)
    return "".join([*lines[: line + 1], *new, *lines[line + 1 :]])


def _above_the_block(lines: list[str], new: list[str]) -> str:
    """`new` at the root, above the generated block, set off by blank lines."""
    at = _generated_line(lines)
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    if at > 0 and lines[at - 1].strip():
        new = ["\n", *new]
    if at < len(lines):
        new = [*new, "\n"]
    return "".join([*lines[:at], *new, *lines[at:]])


def _generated_line(lines: Sequence[str]) -> int:
    for index, line in enumerate(lines):
        if line.startswith(GENERATED_MARKER) or line.startswith("generated:"):
            return index
    return len(lines)


