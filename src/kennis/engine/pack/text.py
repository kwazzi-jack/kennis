"""Editing a pack file as text, keeping what the person wrote.

`pack add`, `pack remove` and `pack update` all change a pack file, and the
person edits it too (Brian, 2026-10-26: "like a package.json with npm, or a
pyproject.toml with uv"). **The file is edited as text, never dumped**:
`yaml.dump` of the parsed pack would lose the editor header, every comment
and the person's key order. Positions come from `yaml.compose`, whose nodes
carry marks, and only the lines concerned change. A caller parses what it
made before it writes, so a defect here is a refusal, never a half-written
file.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Final

import yaml
from yaml.nodes import MappingNode, Node, ScalarNode, SequenceNode

from kennis.engine.errors import InputError, PackInvalid

type Value = str | int | list[str]
type Fields = list[tuple[str, Value]]

GENERATED_MARKER: Final = "# Generated by `kennis pack update` - do not hand-edit."


def read_pack_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError as error:
        raise PackInvalid(f"{path} could not be read: {error}") from error


def composed(text: str) -> MappingNode:
    node = yaml.compose(text)
    if not isinstance(node, MappingNode):
        raise PackInvalid("a pack file is a mapping of sections")
    return node


def child(mapping: MappingNode, key: str) -> tuple[ScalarNode, Node] | None:
    for key_node, value_node in mapping.value:
        if isinstance(key_node, ScalarNode) and key_node.value == key:
            return key_node, value_node
    return None


def node_at(root: MappingNode, keys: Sequence[str]) -> Node | None:
    """The node `keys` names, a digit naming a sequence's item."""
    node: Node = root
    for key in keys:
        if isinstance(node, SequenceNode) and key.isdigit():
            node = node.value[int(key)]
            continue
        if not isinstance(node, MappingNode):
            return None
        found = child(node, key)
        if found is None:
            return None
        node = found[1]
    return node


def last_line(node: Node, lines: Sequence[str]) -> int:
    """The last line holding a character of `node`.

    A block collection's end mark is the next token's position, which can
    be lines further on past comments, so the leaves are asked instead, and
    a line that is blank or only a comment is never counted.
    """
    if isinstance(node, ScalarNode) or getattr(node, "flow_style", False):
        line = (
            node.end_mark.line if node.end_mark.column > 0 else node.end_mark.line - 1
        )
    elif isinstance(node, MappingNode):
        line = max(last_line(value, lines) for pair in node.value for value in pair)
    elif isinstance(node, SequenceNode):
        line = max(last_line(item, lines) for item in node.value)
    else:
        line = node.end_mark.line
    while line > node.start_mark.line and _is_filler(lines[line]):
        line -= 1
    return line


def _is_filler(line: str) -> bool:
    stripped = line.strip()
    return not stripped or stripped.startswith("#")


def rendered(item: Fields, dash: int) -> list[str]:
    """One sequence item: the first key on the dash's line, the rest under
    it. Strings through `json.dumps`, a YAML double-quoted scalar that keeps
    the file ASCII whatever a title holds."""
    lines: list[str] = []
    for position, (key, value) in enumerate(item):
        lead = " " * dash + "- " if position == 0 else " " * (dash + 2)
        if isinstance(value, list):
            lines.append(f"{lead}{key}:\n")
            lines.extend(f"{' ' * (dash + 4)}- {scalar(one)}\n" for one in value)
        else:
            lines.append(f"{lead}{key}: {scalar(value)}\n")
    return lines


def scalar(value: str | int) -> str:
    return str(value) if isinstance(value, int) else json.dumps(value)


def appended(
    text: str, section: Sequence[str], item: Fields, *, single: str | None = None
) -> str:
    """`text` with one item added at the end of the sequence `section` names,
    creating the sequence, and the mapping holding it, where missing."""
    lines = text.splitlines(keepends=True)
    root = composed(text)
    node = node_at(root, section)
    if isinstance(node, SequenceNode) and node.value:
        if node.flow_style:
            raise InputError(
                f"{'.'.join(section)} is written as a flow list; write it as a "
                "block list, one item per line, to add to it"
            )
        # The dash is the first character on the last item's first line.
        dash = dash_column(lines[node.value[-1].start_mark.line])
        new = (
            [f"{' ' * dash}- {scalar(single)}\n"]
            if single is not None
            else rendered(item, dash)
        )
        if _spaced(node, lines):
            new = ["\n", *new]
        at = last_line(node, lines) + 1
        return "".join([*lines[:at], *new, *lines[at:]])

    return _with_a_new_list(text, section, item)


def _with_a_new_list(text: str, section: Sequence[str], item: Fields) -> str:
    """`text` with the list `section` names, which holds no items, made to
    hold `item`: an empty `[]` or a bare key is written out, a missing key
    is added to its mapping, and a missing mapping is made too - the only
    one that can be is `corpus`, because the root always exists."""
    lines = text.splitlines(keepends=True)
    root = composed(text)
    *parents, key = section
    parent = node_at(root, parents) if parents else root
    found = child(parent, key) if isinstance(parent, MappingNode) else None
    if found is not None:
        return _filled(lines, found, item, named=".".join(section))
    if isinstance(parent, MappingNode) and parent.value and not parent.flow_style:
        column = parent.value[0][0].start_mark.column
        new = [f"{' ' * column}{key}:\n", *rendered(item, column + 2)]
        if not parents:
            return _above_the_block(lines, new)
        at = last_line(parent, lines) + 1
        return "".join([*lines[:at], *new, *lines[at:]])
    assert len(parents) == 1, section
    holder = child(root, parents[0])
    new = rendered(item, 4)
    if holder is None:
        return _above_the_block(lines, [f"{parents[0]}:\n", f"  {key}:\n", *new])
    return _filled(lines, holder, [], named=parents[0], inner=[f"  {key}:\n", *new])


def _filled(
    lines: list[str],
    found: tuple[ScalarNode, Node],
    item: Fields,
    *,
    named: str,
    inner: list[str] | None = None,
) -> str:
    """A key whose value is `[]`, `{}` or nothing, given lines below it:
    `item` as its list's first item, or the `inner` lines of a mapping."""
    key_node, value = found
    empty_collection = (
        isinstance(value, SequenceNode | MappingNode)
        and value.flow_style
        and not value.value
    )
    null = isinstance(value, ScalarNode) and value.tag == "tag:yaml.org,2002:null"
    if not (empty_collection or null):
        raise InputError(
            f"{named} is written on one line; write it as a block, one item "
            "per line, to add to it"
        )
    line = key_node.start_mark.line
    if empty_collection:
        text = lines[line]
        lines[line] = (
            text[: value.start_mark.column].rstrip() + text[value.end_mark.column :]
        )
    new = inner if inner is not None else rendered(item, key_node.start_mark.column + 2)
    return "".join([*lines[: line + 1], *new, *lines[line + 1 :]])


def _above_the_block(lines: list[str], new: list[str]) -> str:
    """`new` at the root, above the generated block, set off by blank lines."""
    at = _generated_line(lines)
    if lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    if at > 0 and lines[at - 1].strip():
        new = ["\n", *new]
    if at < len(lines):
        new = [*new, "\n"]
    return "".join([*lines[:at], *new, *lines[at:]])


def _generated_line(lines: Sequence[str]) -> int:
    for index, line in enumerate(lines):
        if line.startswith(GENERATED_MARKER) or line.startswith("generated:"):
            return index
    return len(lines)


def dash_column(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _spaced(sequence: SequenceNode, lines: Sequence[str]) -> bool:
    """Whether the sequence's last two items have a blank line between
    them, so a new item is spaced the same."""
    if len(sequence.value) < 2:
        return False
    before, last = sequence.value[-2], sequence.value[-1]
    between = range(last_line(before, lines) + 1, last.start_mark.line)
    return any(not lines[index].strip() for index in between)


def with_fields_first(
    text: str, section: Sequence[str], index: int, fields: Fields
) -> str:
    """`text` with `fields` at the head of item `index` of the sequence
    `section` names, so they read before what the item already says.

    On the dash's line when a key is there (`- identifier: x` becomes
    `- citekey: ...` over `  identifier: x`); below a dash that stands
    alone, at its keys' column. An item written on one line, `- {...}`,
    is refused: there is no line of its own to give a field.
    """
    lines = text.splitlines(keepends=True)
    item = node_at(composed(text), (*section, str(index)))
    if not isinstance(item, MappingNode) or item.flow_style or not item.value:
        raise PackInvalid(
            f"entry {index + 1} of {'.'.join(section)} is written on one line; "
            "write it one key per line, as `- identifier: ...` with each "
            "other key below it, for kennis to add to it"
        )
    first = item.value[0][0]
    line = first.start_mark.line
    column = first.start_mark.column
    held = lines[line]
    if held[:column].strip() == "-":
        new = rendered(fields, column - 2)
        lines[line] = " " * column + held[column:]
    else:
        new = rendered(fields, column - 2)
        new[0] = " " * column + new[0][column:]
    return "".join([*lines[:line], *new, *lines[line:]])


